// Runs before the Hugo build on Netlify (see netlify.toml). Hugo leaves future-dated posts out
// of the build, so this lists their dates for the scheduled function
// netlify/functions/publish-scheduled.mjs, which rebuilds the site once one of them is due.
import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const now = Date.now();
const dates = new Set();

function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else if (/\.(html|md)$/.test(name)) check(path);
  }
}

function check(path) {
  const frontMatter = readFileSync(path, "utf8").match(/^\+\+\+\r?\n([\s\S]*?)\r?\n\+\+\+/);
  if (!frontMatter || /^draft\s*=\s*true\b/m.test(frontMatter[1])) return;
  const date = frontMatter[1].match(/^date\s*=\s*"([^"]+)"/m);
  const time = date ? Date.parse(date[1]) : NaN;
  if (time > now) dates.add(new Date(time).toISOString());
}

for (const lang of readdirSync("content")) {
  const posts = join("content", lang, "post");
  try { statSync(posts); } catch { continue; }
  walk(posts);
}

const list = [...dates].sort();
mkdirSync("netlify/generated", { recursive: true });
writeFileSync(
  "netlify/generated/scheduled-posts.mjs",
  `// Generated by netlify/scheduled-posts.mjs at ${new Date(now).toISOString()}.\nexport const dates = ${JSON.stringify(list)};\n`,
);
console.log(`Scheduled posts waiting to be published: ${list.length ? list.join(", ") : "none"}`);
